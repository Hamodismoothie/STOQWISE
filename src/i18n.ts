export type Locale = (typeof LOCALES)[number]["code"];
export type AvailableLocale = "en" | "sv";
export const DEFAULT_LOCALE: AvailableLocale = "en";
export const COOKIE_NAME = "lr_lang";

export function localeInfo(code: string): (typeof LOCALES)[number] | undefined {
  return LOCALES.find((l) => l.code === code);
}

export function isAvailableLocale(code: string | undefined | null): code is AvailableLocale {
  const info = localeInfo(code ?? "");
  return Boolean(info?.available);
}

export function dirFor(locale: Locale): "ltr" | "rtl" {
  return localeInfo(locale)?.dir ?? "ltr";
}

export function intlFor(locale: Locale): string {
  return localeInfo(locale)?.intl ?? "en-US";
}

/** Reads the persisted choice from a Cookie header. Unknown or unavailable codes fall back to English. */
export function localeFromCookie(header: string | null | undefined): AvailableLocale {
  if (!header) return DEFAULT_LOCALE;
  for (const part of header.split(";")) {
    const [name, ...rest] = part.trim().split("=");
    if (name !== COOKIE_NAME) continue;
    const value = decodeURIComponent(rest.join("=")).trim();
    if (isAvailableLocale(value)) return value;
  }
  return DEFAULT_LOCALE;
}

export function cookieFor(locale: AvailableLocale): string {
  return `${COOKIE_NAME}=${locale}; Path=/; Max-Age=31536000; SameSite=Lax`;
}

/** Only same-site, absolute paths are accepted as a return target. */
export function safeNext(next: string | null | undefined): string {
  if (!next) return "/";
  if (!next.startsWith("/") || next.startsWith("//")) return "/";
  if (/[\\\u0000-\u001f]/.test(next)) return "/";
  return next;
}

/* ------------------------------------------------------------- formatting */

export function formatNumber(locale: Locale, value: number, decimals = 0): string {
  return new Intl.NumberFormat(intlFor(locale), {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(value);
}

/**
 * Amounts are always SEK. The language changes separators and grouping only —
 * never the currency, the amount or the number of decimals (whole kronor).
 */
export function formatSek(locale: Locale, value: number): string {
  return `SEK ${new Intl.NumberFormat(intlFor(locale), { maximumFractionDigits: 0 }).format(value)}`;
}

export function formatDate(locale: Locale, iso: string): string {
  return new Date(iso).toLocaleDateString(intlFor(locale), { year: "numeric", month: "long", day: "numeric" });
}

