/**
 * The public crawl surface.
 *
 * One list decides which pages search engines may index, so `robots.txt`,
 * `sitemap.xml` and the tests cannot drift apart. The language is chosen with a
 * cookie rather than a URL segment, so every page has exactly one address.
 *
 * Private routes are listed explicitly because they either require a session or
 * return JSON; none of them is useful in an index.
 */
import { config } from "./config.ts";

export const PUBLIC_PAGES = [
  "/",
  "/produkt",
  "/priser",
  "/om-oss",
  "/kontakt",
  "/kom-igang",
  "/hjalp",
  "/integritet",
  "/villkor",
] as const;

export const PRIVATE_PREFIXES = [
  "/app",
  "/admin",
  "/utvecklare",
  "/api/",
  "/logga-in",
  "/logga-ut",
  "/skapa-konto",
  "/glomt-losenord",
] as const;

// Ta bort alla avslutande snedstreck så att en origin med t.ex. "https://exempel.se//"
// inte ger dubbla snedstreck när den sätts ihop med ett sidformat som börjar med "/".
const origin = (): string => config.appOrigin.replace(/\/+$/, "");

/**
 * Absolute address for a page. A query string is dropped: `?sort=…` is the
 * same document as the page itself, so it must not create a second address.
 */
export function absoluteUrl(path: string): string {
  const clean = path.split(/[?#]/)[0] ?? "/";
  const collapsed = clean.replace(/\/{2,}/g, "/");
  const normalised = collapsed === "" ? "/" : collapsed;
  return normalised === "/" ? `${origin()}/` : `${origin()}${normalised.replace(/\/$/, "")}`;
}

/** Social card, 1200×630, generated by `scripts/make-og.ts`. */
export const OG_IMAGE_PATH = "/brand/stoqwise-og.png";

/** Logotypen som används i strukturerad data. Samma fasta fil som i sidhuvudet. */
export const LOGO_PATH = "/brand/stoqwise-logo.svg";

/**
 * Error pages and the session routes must not enter an index. Everything else
 * in the public surface may.
 */
export function isIndexable(path: string): boolean {
  const clean = path.split(/[?#]/)[0] || "/";
  if (clean === "/404") return false;
  return !PRIVATE_PREFIXES.some(
    (prefix) => clean === prefix || clean.startsWith(`${prefix}/`) || (prefix.endsWith("/") && clean.startsWith(prefix)),
  );
}

const xmlEscape = (value: string): string =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function robotsTxt(): string {
  return [
    "User-agent: *",
    "Allow: /",
    ...PRIVATE_PREFIXES.map((path) => `Disallow: ${path}`),
    "",
    `Sitemap: ${origin()}/sitemap.xml`,
    "",
  ].join("\n");
}

export function sitemapXml(): string {
  // Använd samma adressbyggare som kanoniska länkar i stället för att sätta
  // ihop origin och sidformat på nytt här.
  const urls = PUBLIC_PAGES.map((path) => `  <url><loc>${xmlEscape(absoluteUrl(path))}</loc></url>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

/**
 * Strukturerad data för organisation och webbplats. Bara namn, logotyp och
 * adress – allt annat vore påhittat. Adresserna kommer från absoluteUrl(), samma
 * byggare som kanonisk länk och sitemap, så de tre kan inte glida isär.
 */
export function structuredDataJsonLd(): string {
  const site = absoluteUrl("/");
  const data = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Organization",
        name: "STOQWISE",
        url: site,
        logo: absoluteUrl(LOGO_PATH),
      },
      {
        "@type": "WebSite",
        name: "STOQWISE",
        url: site,
      },
    ],
  };
  // "<" escapas i JSON så att en oväntad teckenföljd i app-origin inte kan
  // avsluta script-elementet i HTML:en.
  return JSON.stringify(data).replace(/</g, "\\u003c");
}
